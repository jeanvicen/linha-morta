/**
 * PWA installation and update handling. The game never claims to be installed just because a
 * button was clicked: it reports the browser's own outcome and the `appinstalled` event.
 */
import { Emitter } from '../../core/events';

interface BeforeInstallPromptEvent extends Event {
  prompt(): Promise<void>;
  readonly userChoice: Promise<{ outcome: 'accepted' | 'dismissed'; platform: string }>;
}

interface InstallEvents {
  change: undefined;
  installed: undefined;
}

export type InstallPlatform = 'ios' | 'android' | 'desktop';

export class InstallManager extends Emitter<InstallEvents> {
  private deferred: BeforeInstallPromptEvent | null = null;
  readonly platform: InstallPlatform;
  private installedFlag = false;

  constructor(platform: InstallPlatform) {
    super();
    this.platform = platform;
    window.addEventListener('beforeinstallprompt', (event) => {
      event.preventDefault();
      this.deferred = event as BeforeInstallPromptEvent;
      this.emit('change', undefined);
    });
    window.addEventListener('appinstalled', () => {
      this.deferred = null;
      this.installedFlag = true;
      this.emit('installed', undefined);
      this.emit('change', undefined);
    });
  }

  /** True when running as an installed app (standalone display mode). */
  get standalone(): boolean {
    const nav = navigator as Navigator & { standalone?: boolean };
    return window.matchMedia?.('(display-mode: standalone)').matches || window.matchMedia?.('(display-mode: fullscreen)').matches || nav.standalone === true;
  }

  /** The browser exposed a programmatic install prompt. */
  get canPrompt(): boolean {
    return this.deferred !== null;
  }

  /** Whether to show an install entry at all (prompt available, or manual instructions useful). */
  get offerInstall(): boolean {
    if (this.standalone || this.installedFlag) return false;
    return this.canPrompt || this.platform === 'ios' || this.platform === 'android' || this.platform === 'desktop';
  }

  async prompt(): Promise<'accepted' | 'dismissed' | 'unavailable'> {
    const event = this.deferred;
    if (!event) return 'unavailable';
    try {
      await event.prompt();
      const choice = await event.userChoice;
      this.deferred = null;
      this.emit('change', undefined);
      return choice.outcome;
    } catch {
      return 'unavailable';
    }
  }
}

export interface UpdateHooks {
  onNeedRefresh: (apply: () => void) => void;
  onOfflineReady: () => void;
}

/** Registers the service worker generated by vite-plugin-pwa (production builds only). */
export async function registerServiceWorker(hooks: UpdateHooks): Promise<void> {
  if (!('serviceWorker' in navigator) || import.meta.env.DEV) return;
  try {
    const { registerSW } = await import('virtual:pwa-register');
    const update = registerSW({
      immediate: true,
      onNeedRefresh() {
        hooks.onNeedRefresh(() => void update(true));
      },
      onOfflineReady() {
        hooks.onOfflineReady();
      },
      onRegisterError(error: unknown) {
        console.warn('[pwa] service worker registration failed', error);
      },
    });
  } catch (error) {
    console.warn('[pwa] service worker unavailable', error);
  }
}
